places = ["Kyoto", "Bali", "Istanbul", "Reykjavik", "Machu Picchu"]
print("Daftar asli:", places)
print("Urut alfabetis:", sorted(places))
print("Asli tetap:", places)
print("Urut terbalik alfabetis:", sorted(places, reverse=True))
print("Asli tetap:", places)
places.reverse()
print("Setelah reverse:", places)
places.reverse()
print("Kembali seperti semula:", places)
places.sort()
print("Sort permanen:", places)
places.sort(reverse=True)
print("Sort terbalik permanen:", places)
